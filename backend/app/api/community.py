"""Community routes - the five things a person can do on their phone.

Every response here answers the three questions the specification demands the
community side never leave open: did you receive it, who is doing what, when will
I hear again. The text is generated by `services.communication`, so it is the same
words in English and Nepali and never a model improvising a promise.
"""

