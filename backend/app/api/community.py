router = APIRouter(prefix="/community", tags=["community"])


@router.post("/reports")
def file_report(
    body: ReportIn,
    user: User = Depends(require_permission("community:report")),
    db: Session = Depends(get_db),
) -> dict:
    report, linked, request = community_service.submit_report(
        db,
        user=user,
        message=body.message,
        report_type=body.report_type,
        incident_type=body.incident_type,
        latitude=body.latitude,
        longitude=body.longitude,
        location_text=body.location_text,
        people_count=body.people_count,
        medical_need=body.medical_need,
        injuries=body.injuries,
        language=body.language,
        attachments=[a.model_dump() for a in body.attachments],
        client_timestamp=body.client_timestamp,
        submitted_offline=body.submitted_offline,
        needs_help=body.needs_help,
        help_types=body.help_types,
        incident_id=body.incident_id,
        immediate_danger=body.immediate_danger,
    )
    return {
        "report": community_service.report_to_dict(db, report),
        "incident": _public_incident(linked),
        "assistance_request": assistance.to_dict(db, request, victim_view=True) if request else None,
        "answer": _answer(report, linked, request),
        "what_happens_next": (
            communication.next_step(request.status, body.language)
            if request
            else _report_next_step(report, linked)
        ),
        "demo_mode": bool(report.demo_scenario_id),
    }


def _answer(report, linked, request) -> str:
    """One sentence telling the person what their message became."""
    language = report.language
    carried_on = (report.structured or {}).get("help_carried_on")
    if request is not None and carried_on:
        # Saying "a request was opened" when it was already open would be a lie about
        # the state of their own case, and the case number is the part they keep.
        return (
            f"तपाईंको अघिल्लो अनुरोध {carried_on} अझै खुला छ। दोहोरो सन्देशले त्यही अनुरोधको प्राथमिकता बढाएको छ।"
            if language == "ne"
            else f"Your earlier request {carried_on} is still open. This message raised its priority instead of opening a second case."
        )
    if request is not None:
        return (
            f"तपाईंको रिपोर्ट दर्ता भयो र {request.ref_code} सन्दर्भसहित सहयोग अनुरोध खोलिएको छ।"
            if language == "ne"
            else f"Your report is logged and a help request was opened for you as {request.ref_code}."
        )
    if report.duplicate_status == "duplicate":
        return (
            "तपाईंको यही जानकारी पहिले नै आइसकेको छ, नयाँ अनुरोध खोलिएन।"
            if language == "ne"
            else "The same information was already received, so no second request was opened."
        )
    if linked is not None:
        return (
            f"तपाईंको रिपोर्ट {linked.title} सँग जोडिएको छ।"
            if language == "ne"
            else f"Your report was attached to {linked.title}."
        )
    return (
        "तपाईंको रिपोर्ट दर्ता भयो, नजिकको कुनै घटनासँग अहिलेसम्म मेल खाएन।"
        if language == "ne"
        else "Your report is logged. It did not match any incident we know of yet."
    )


def _report_next_step(report, linked) -> str:
    """What happens to a report that did not become a help request. Being explicit
    here is what stops a person assuming help is on the way because they posted."""
    if linked is not None:
        return (
            "यो जानकारी आधिकारिक टोलीले हेरिरहेको घटनासँग जोडिएको छ।"
            if report.language == "ne"
            else "It has been added to an incident the Response Center is already watching."
        )
    return (
        "आधिकारिक निकायले हेर्ने पङ्क्तिमा राखिएको छ; यो अझै आधिकारिक सूचना होइन।"
        if report.language == "ne"
        else "It is queued for an operator to review. It is not an official warning by itself."
    )


def _public_incident(incident) -> dict | None:
    """Community users may see that their report joined a known situation, and its
    official status - never another person's private case details."""
    if incident is None:
        return None
    return {
        "id": incident.id,
        "ref_code": incident.ref_code,
        "title": incident.title,
        "incident_type": incident.incident_type,
        "district": incident.district,
        "evidence_state": incident.evidence_state,
        "official": incident.official_confirmation,
        "last_updated_at": iso(incident.last_updated_at),
        # The record's own address, not a screen route - see the note in api/incidents.py. A
        # community account gets the public projection of that endpoint, not the console one.
        "api_url": f"/api/incidents/{incident.id}",
    }


